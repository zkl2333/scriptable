export const measurePixelText = (text, scale) =>
  text.length === 0 ? 0 : text.length * GLYPH_ADVANCE * scale - scale;

export const drawPixelText = (context, text, x, y, scale, color) => {
  context.setFillColor(color);
  const startX = Math.round(x);
  const startY = Math.round(y);
  let cursor = startX;
  for (const char of String(text).toUpperCase()) {
    const glyph = PIXEL_GLYPHS[char] || PIXEL_GLYPHS[' '];
    glyph.forEach((row, rowIndex) => {
      for (const [columnIndex, cell] of [...row].entries()) {
        if (cell !== '#') continue;
        context.fillRect(new Rect(
          cursor + columnIndex * scale,
          startY + rowIndex * scale,
          scale,
          scale
        ));
      }
    });
    cursor += GLYPH_ADVANCE * scale;
  }
  return cursor - startX - scale;
};
